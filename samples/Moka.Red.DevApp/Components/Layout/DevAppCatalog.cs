	public static string PageName(string href) => MokaNavEntry.Find(Entries, href)?.Label ?? string.Empty;

	private static MokaNavEntry Page(string group, string label, string route, MokaIconDefinition icon, string more = "")
	{
		string page = route.Trim('/');
		IEnumerable<string> shown = Components
			.Where(component => string.Equals(PathOf(component.Href), page, StringComparison.Ordinal))
			.Select(component => component.Name);
		return new MokaNavEntry(group, label, route, icon, string.Join(' ', shown.Append(more)).Trim());
	}

	private static string PathOf(string href) => href.Split('?', '#')[0].Trim('/');
